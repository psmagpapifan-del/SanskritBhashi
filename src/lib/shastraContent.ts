/**
 * Shastra Study question bank — topic-based, across several texts.
 *
 * Each topic holds 7-9 questions mixing six kinds:
 *   meaning  – what a verse or phrase says
 *   grammar  – case, tense/mood, suffix of a word in the verse
 *   sandhi   – how a joined form splits
 *   fill     – complete the verse
 *   source   – which text a verse comes from
 *   concept  – the idea taught
 *
 * Content is in English for now; the UI around it is localized.
 * Verse references follow the standard (Gita Press / critical edition) numbering.
 */

export type ShastraKind = "meaning" | "grammar" | "sandhi" | "fill" | "source" | "concept";

export interface ShastraQuestion {
  id: string;
  kind: ShastraKind;
  prompt: string;
  /** Devanagari passage the question is about (optional). */
  verse?: string;
  /** Reference for the passage, e.g. "Bhagavad Gītā 2.47". */
  ref?: string;
  options: string[];
  correctIndex: number;
  /** Nudge shown in practice mode after a wrong first attempt. */
  hint: string;
  /** Shown after the question is answered. */
  explanation: string;
}

export interface ShastraTopic {
  id: string;
  text: string;
  title: string;
  summary: string;
  questions: ShastraQuestion[];
}

const q = (topic: string, n: number, data: Omit<ShastraQuestion, "id">): ShastraQuestion => ({ id: `${topic}-${n}`, ...data });

